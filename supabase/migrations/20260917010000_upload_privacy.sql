-- ⚠️ 적용 순서: 20260916100000_archive_extras.sql **다음에** 적용한다.
--    이 파일 자체는 그 파일에 기대지 않지만(컬럼 하나를 더할 뿐이다), 이
--    컬럼을 채우는 작업(촬영 정보 채우기)이 그 파일의 `exif_checked_at` 등을
--    함께 쓰므로 순서대로 두는 편이 헷갈리지 않는다.
--
-- 원본에 위치 정보가 남았는지 적어 두는 표시 하나.
--
-- 배경: Cloudinary 원본은 딜리버리 URL에서 변환 구간만 빼면 누구나 받을 수
-- 있고, 원본의 EXIF에는 찍은 자리의 정밀한 GPS가 들어 있었다. 이제 관리
-- 화면과 CLI는 **올리기 전에** 파일에서 위치 정보를 지운다(`lib/exif-strip.ts`).
-- 이 컬럼은 그 뒤의 방어선이다: 촬영 정보 채우기가 Cloudinary에서 원본의
-- 메타데이터를 읽을 때 GPS·장소 태그가 아직 있으면 true, 없으면 false를 적는다.
-- 다른 경로(콘솔 직접 업로드 등)로 들어온 원본을 개요의 데이터 점검이 "위치
-- 정보가 남은 원본"으로 띄운다. **자동으로 지우거나 고치지 않는다.**
--
-- null은 "아직 모름"이다. 채우기가 이미 지나간 기존 사진은 null로 남고,
-- 개요에서 사진별로 "다시 확인"하면 채워진다.
--
-- 좌표는 여기에도 **두지 않는다**(archive_extras의 원칙 그대로). 불리언 하나라
-- 공개 조회(`select('*')`)에 실려 나가도 새로 알려 주는 것이 없다 — 원본 자체가
-- 이미 공개돼 있고, 고칠 곳은 원본이다.
--
-- 추가만 한다(nullable, 기본값 없음). 지금 배포된 코드와 호환되고, 코드가 먼저
-- 배포돼도 채우기는 컬럼이 없다는 오류(PGRST204)를 받으면 표시 없이 계속한다.
